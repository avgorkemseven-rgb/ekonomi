// Generates dist/tokens.css (CSS custom properties, light + dark) from the compiled tokens.
const fs = require('node:fs');
const path = require('node:path');
const { colors, radii, spacing } = require('../dist/index.js');

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const vars = (scheme) =>
  Object.entries(scheme)
    .map(([k, v]) => `  --k-${kebab(k)}: ${v};`)
    .join('\n');
const scalar = (prefix, obj) =>
  Object.entries(obj)
    .map(([k, v]) => `  --k-${prefix}-${k}: ${v}px;`)
    .join('\n');

const css = `/* Generated by @kleps/tokens — do not edit. */
:root {
${vars(colors.light)}
${scalar('radius', radii)}
${scalar('space', spacing)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root {
${vars(colors.dark)}
    color-scheme: dark;
  }
}
:root[data-theme='light'] {
${vars(colors.light)}
  color-scheme: light;
}
:root[data-theme='dark'] {
${vars(colors.dark)}
  color-scheme: dark;
}
`;
fs.writeFileSync(path.join(__dirname, '..', 'dist', 'tokens.css'), css);
console.info('tokens.css written');
